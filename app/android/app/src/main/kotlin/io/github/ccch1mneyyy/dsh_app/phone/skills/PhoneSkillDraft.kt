package io.github.ccch1mneyyy.dsh_app.phone.skills

import io.github.ccch1mneyyy.dsh_app.phone.PhoneScreen
import io.github.ccch1mneyyy.dsh_app.phone.PhoneUiText

/** Explicit local rendering only. No model, filesystem, logger or automatic invocation. */
object PhoneSkillDraft {
    enum class Reason { CONFIRMATION_REQUIRED, TRACE_UNAVAILABLE, TRACE_INELIGIBLE, INVALID_NAME, TOO_LARGE }
    sealed interface Result
    sealed interface Ready : Result {
        val owner: PhoneTaskTrace.OwnerKey
        val skillName: String
        val markdown: String
    }
    data class Rejected(val reason: Reason) : Result
    private class Document(override val owner: PhoneTaskTrace.OwnerKey, override val skillName: String,
        override val markdown: String) : Ready

    /**
     * Name is generated by native code, not a path/title/free-text input. Edits require a later
     * validated revision. The document's prose follows the app language through [ui]; the anchor
     * words it tells the model to look for stay as the app's own screen words, and every
     * placeholder (`{{goal}}`, `{{app_1}}`, `{{check_1}}`, `{{target_1}}`, `{{input_1}}`) is fixed.
     */
    fun render(trace: PhoneTaskTrace.Snapshot?, skillName: String, userConfirmed: Boolean, userEdited: Boolean = false,
               ui: PhoneUiText = PhoneUiText.DEFAULT): Result {
        if (!userConfirmed) return Rejected(Reason.CONFIRMATION_REQUIRED)
        if (trace == null) return Rejected(Reason.TRACE_UNAVAILABLE)
        if (!trace.canDraft) return Rejected(Reason.TRACE_INELIGIBLE)
        if (!Regex("phone-task-[a-f0-9]{32}").matches(skillName)) return Rejected(Reason.INVALID_NAME)
        val markdown = buildString {
            append("---\nname: ").append(skillName)
            append("\ndescription: ").append(
                ui.get("phone_skill_doc_description", "手机任务的本地参数化步骤，使用前核对目标与环境")).append('\n')
            append("disable-model-invocation: true\nuser-invocable: true\n---\n\n")
            append(ui.get("phone_skill_doc_goals_block", "# 手机任务步骤草稿\n\n## 目标与参数\n\n"))
            if (userEdited) append(ui.get("phone_skill_doc_edited",
                "这是用户重新整理的步骤模板，顺序可能不同于原任务；不是可执行的历史路线。\n"))
            append(ui.get("phone_skill_doc_goal",
                "目标：{{goal}}。所有参数在本次使用时由用户提供；不要把个人值写回技能。\n"))
            append(ui.get("phone_skill_doc_requirements",
                "应用、版本及登录前提未保留：{{application_requirements}}。先核对当前应用与权限。\n"))
            append(ui.get("phone_skill_doc_placeholders",
                "目标、输入和检查点占位符尚未填写时，停止并询问用户。\n\n"))
            append(ui.get("phone_skill_doc_steps_block", "## 步骤\n\n"))
            trace.steps.forEachIndexed { index, step ->
                val n = index + 1
                val screen = if (step.screen == PhoneScreen.BACKGROUND)
                    ui.get("phone_skill_doc_background_screen", "后台屏")
                else ui.get("phone_skill_doc_main_screen", "主屏")
                append(ui.get("phone_skill_doc_step",
                    "%1\$s. 在%2\$s重新观察并确认应用 {{app_%3\$s}}；%4\$s。\n", n, screen, n, instruction(step, n, ui)))
                append(ui.get("phone_skill_doc_check",
                    "   核对 {{check_%1\$s}}，不能只凭工具返回正常判断业务完成。历史记录仅表明请求已交给驱动/系统并返回接受；", n))
                append(if (step.postObservationAvailable) ui.get("phone_skill_doc_post_seen",
                    "曾取得允许读取的后置观察，未验证预期变化。\n")
                    else ui.get("phone_skill_doc_post_none", "没有可用的安全后置观察证据。\n"))
            }
            append(ui.get("phone_skill_doc_stop_block", "\n## 必须停下的情况\n\n"))
            append(ui.get("phone_skill_doc_stop_reread",
                "每步都重新读取页面，不复用旧屏幕号、元素号或坐标。目标不唯一、页面/应用不符、权限改变或没有可核对结果时停下，请用户或模型重新判断。\n"))
            append(ui.get("phone_skill_doc_stop_irreversible",
                "发送、提交、删除、确认付款以及任何不可逆动作必须重新请求用户确认；历史批准与本次保存确认不授予执行许可。\n"))
            append(ui.get("phone_skill_doc_stop_error",
                "动作返回错误、超时或结果不明时，先观察，不自动重放同一步。密码、验证码与秘密内容由用户处理，不写进技能。\n"))
            append(ui.get("phone_skill_doc_stop_template",
                "这是一份待核对的本地步骤模板，不是自动回放程序，也没有经过跨版本成功验证。\n"))
        }
        if (markdown.toByteArray(Charsets.UTF_8).size > PhoneTaskTrace.MAX_BYTES) return Rejected(Reason.TOO_LARGE)
        return Document(trace.owner, skillName, markdown)
    }

    /** Reviewed native public route summary only; no MethodChannel accepts this text.
     * The caller must bind this exact preview and bundle at a new editor revision. */
    internal fun withRouteSummary(document: Ready, summary: String, ui: PhoneUiText = PhoneUiText.DEFAULT): Ready? {
        val markdown = buildString {
            append("---\nname: ").append(document.skillName)
            append("\ndescription: ").append(
                ui.get("phone_skill_doc_route_description", "本机公共路线，使用时重新核对应用、目标与许可")).append('\n')
            append("disable-model-invocation: true\nuser-invocable: true\n---\n\n")
            append(ui.get("phone_skill_doc_route_block", "# 公共路线预览\n\n")).append(summary)
            append(ui.get("phone_skill_doc_route_save_note",
                "\n\n保存确认不授予执行权限。任一步前置、唯一目标、许可或后置不符就停止交回模型；失败或未知不自动重复。\n"))
            append(ui.get("phone_skill_doc_route_edit_note",
                "不可逆操作仍须本次独立确认。编辑步骤会移除此数据路线。\n"))
        }
        if (markdown.toByteArray(Charsets.UTF_8).size > PhoneTaskTrace.MAX_BYTES) return null
        return Document(document.owner, document.skillName, markdown)
    }

    private fun instruction(step: PhoneTaskTrace.Step, n: Int, ui: PhoneUiText): String {
        val target = step.anchor?.let {
            ui.get("phone_skill_doc_anchor_target", "固定动作词「%1\$s」（仍须核对唯一目标）", anchor(it))
        } ?: "{{target_$n}}"
        return when (step.action) {
            PhoneTaskTrace.Action.OPEN_APP -> ui.get("phone_skill_doc_action_open", "打开用户指定的应用")
            PhoneTaskTrace.Action.TAP -> ui.get("phone_skill_doc_action_tap", "点击%1\$s", target)
            PhoneTaskTrace.Action.LONG_TAP -> ui.get("phone_skill_doc_action_long_tap", "长按%1\$s", target)
            PhoneTaskTrace.Action.TYPE -> ui.get("phone_skill_doc_action_type", "向%1\$s 输入 {{input_%2\$s}}", target, n)
            PhoneTaskTrace.Action.TYPE_SUBMIT -> ui.get("phone_skill_doc_action_type_submit",
                "向%1\$s 输入 {{input_%2\$s}}，提交前重新确认", target, n)
            PhoneTaskTrace.Action.SCROLL_UP -> ui.get("phone_skill_doc_action_scroll_up",
                "向上滚动用户确认的区域 {{target_%1\$s}}", n)
            PhoneTaskTrace.Action.SCROLL_DOWN -> ui.get("phone_skill_doc_action_scroll_down",
                "向下滚动用户确认的区域 {{target_%1\$s}}", n)
            PhoneTaskTrace.Action.SCROLL_LEFT -> ui.get("phone_skill_doc_action_scroll_left",
                "向左滚动用户确认的区域 {{target_%1\$s}}", n)
            PhoneTaskTrace.Action.SCROLL_RIGHT -> ui.get("phone_skill_doc_action_scroll_right",
                "向右滚动用户确认的区域 {{target_%1\$s}}", n)
            PhoneTaskTrace.Action.KEY_BACK -> ui.get("phone_skill_doc_action_key_back", "按返回键")
            PhoneTaskTrace.Action.KEY_HOME -> ui.get("phone_skill_doc_action_key_home", "回到桌面")
            PhoneTaskTrace.Action.KEY_RECENTS -> ui.get("phone_skill_doc_action_key_recents", "打开最近任务")
            PhoneTaskTrace.Action.KEY_NOTIFICATIONS -> ui.get("phone_skill_doc_action_key_notifications", "打开通知栏")
        }
    }

    /** The words drawn on the screen: identity, never presentation, so they stay as recorded. */
    // l10n:keep agent screen anchor words
    private fun anchor(value: PhoneTaskTrace.Anchor): String = when (value) {
        PhoneTaskTrace.Anchor.SEARCH -> "搜索"
        PhoneTaskTrace.Anchor.NEXT -> "下一步"
        PhoneTaskTrace.Anchor.BACK -> "返回"
        PhoneTaskTrace.Anchor.CANCEL -> "取消"
        PhoneTaskTrace.Anchor.CONFIRM -> "确认"
        PhoneTaskTrace.Anchor.SAVE -> "保存"
        PhoneTaskTrace.Anchor.SEND -> "发送"
        PhoneTaskTrace.Anchor.SUBMIT -> "提交"
        PhoneTaskTrace.Anchor.DELETE -> "删除"
    }
}
